if __name__ == "__main__":
    # Создаём экземпляр памяти с рабочей памятью на 7 элементов
    mem = HumanLikeMemory(working_capacity=7)

    print("=== 1. Кодирование новой информации ===")
    # Эпизодическое воспоминание с эмоцией и контекстом (запомнится лучше)
    mem.encode(
        "Вчера вечером я гулял в парке и встретил старого друга",
        context={"place": "парк", "time": "вечер"},
        emotion=0.7,
        deep=True,
    )

    # Семантические факты (знания)
    mem.encode("Столица Франции — Париж", mem_type="semantic", emotion=0.1)
    mem.encode("Код на Python пишется с отступами", mem_type="semantic")

    # Ещё одно событие
    mem.encode("На встрече обсуждали нейронные сети и память", emotion=0.4)

    # Повторяем информацию в рабочей памяти (rehearsal)
    mem.rehearse()
    print("Состояние после кодирования:", mem.stats())

    print("\n=== 2. Сон (консолидация) ===")
    mem.simulate_sleep()
    print("Состояние после сна:", mem.stats())

    print("\n=== 3. Извлечение воспоминания (реконструкция) ===")
    rec = mem.retrieve("что было в парке?", k=3, reconstruct=True)
    print("Собранное воспоминание:", rec["reconstructed"])
    print("Исходные фрагменты:", rec["fragments"])

    print("\n=== 4. Прошло время — забывание ===")
    mem.forget(hours_passed=48)  # прошло двое суток
    print("Состояние после забывания:", mem.stats())

    rec2 = mem.retrieve("Париж", k=2)
    print("Семантическое воспоминание:", rec2["fragments"])
