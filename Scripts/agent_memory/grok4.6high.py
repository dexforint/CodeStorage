# =============================================================================
# СИМУЛЯЦИЯ ЧЕЛОВЕЧЕСКОЙ ПАМЯТИ
# =============================================================================
# Этот код — упрощённая компьютерная модель того, как работает человеческая память.
# Он НЕ является точной копией мозга, а инженерной имитацией основных процессов:
#   - Кодирование (превращение информации в «след»)
#   - Хранение в разных «хранилищах» (сенсорная → рабочая → долговременная)
#   - Извлечение с реконструкцией (память не записывает видео, а собирает воспоминание заново)
#   - Забывание по кривой Эббингауза + интерференция
#   - Укрепление следов при повторении и во сне
#
# Используются векторы (эмбеддинги) для семантического сходства — это аналог того,
# как мозг кодирует смысл, а не точные слова.
# =============================================================================

import numpy as np
from datetime import datetime, timedelta
from collections import deque
from typing import List, Dict, Optional, Any
import hashlib

# -----------------------------------------------------------------------------
# ПОДГОТОВКА ЭМБЕДДИНГОВ (векторного представления текста)
# -----------------------------------------------------------------------------
# Эмбеддинг — это числовой вектор, который «кодирует» смысл текста.
# Похожие по смыслу фразы получают близкие векторы.
# Это имитирует то, как мозг превращает сенсорную информацию в нейронный паттерн.
try:
    from sentence_transformers import SentenceTransformer

    # Загружаем предобученную модель (маленькая и быстрая)
    _model = SentenceTransformer("all-MiniLM-L6-v2")
    USE_REAL_EMB = True
except ImportError:
    USE_REAL_EMB = False
    print(
        "Библиотека sentence-transformers не установлена. "
        "Будет использоваться упрощённый dummy-эмбеддинг. "
        "Для лучшего качества: pip install sentence-transformers"
    )


def get_embedding(text: str) -> np.ndarray:
    """
    Кодирование текста в вектор (аналог нейронного представления в мозге).

    Если есть настоящая модель — получаем семантический эмбеддинг.
    Иначе — создаём псевдослучайный, но ДЕТЕРМИНИРОВАННЫЙ вектор по хешу текста
    (чтобы один и тот же текст всегда давал один и тот же вектор).
    """
    if USE_REAL_EMB:
        return _model.encode(text, convert_to_numpy=True)

    # Dummy-режим: делаем вектор фиксированной длины 384 (как у MiniLM)
    h = int(hashlib.md5(text.encode("utf-8")).hexdigest(), 16)
    rng = np.random.RandomState(h % (2**32))
    return rng.rand(384).astype(np.float32)


def cosine_sim(a: np.ndarray, b: np.ndarray) -> float:
    """
    Косинусное сходство двух векторов (от -1 до 1, обычно 0–1 для эмбеддингов).

    Это мера того, насколько два «воспоминания» похожи по смыслу.
    Используется при извлечении: мозг тоже ищет по ассоциациям и ключам,
    а не перебирает всё подряд.
    """
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


# =============================================================================
# ОСНОВНОЙ КЛАСС — ИМИТАЦИЯ ПАМЯТИ
# =============================================================================
class HumanLikeMemory:
    """
    Класс, моделирующий основные системы человеческой памяти.

    Структура:
      - sensory   : сенсорная память (очень краткая, доли секунды – секунды)
      - working   : рабочая/кратковременная память (ограничена ~7 элементами, закон Миллера)
      - long_term : долговременная память (почти без лимита)

    Каждый «след» памяти — это словарь с содержимым, вектором, силой, эмоцией,
    временем создания, количеством обращений и т.д.
    """

    def __init__(self, working_capacity: int = 7):
        # Сенсорная память: очень маленький буфер, быстро перезаписывается
        # (как иконическая зрительная или эхоическая слуховая память)
        self.sensory = deque(maxlen=3)

        # Рабочая память: ограниченный объём (классические 7±2 элемента).
        # Когда переполняется — старые элементы вытесняются (как в реальной жизни).
        self.working = deque(maxlen=working_capacity)

        # Долговременная память: список следов. Здесь хранятся консолидированные воспоминания.
        self.long_term: List[Dict[str, Any]] = []

        # Текущее «время» симуляции (нужно для расчёта давности и забывания)
        self.now = datetime.now()

    def _make_memory(
        self,
        content: str,
        mem_type: str = "episodic",
        emotion: float = 0.0,
        context: Optional[Dict] = None,
        deep_processing: bool = False,
    ) -> Dict[str, Any]:
        """
        Создаёт один «след памяти» (memory trace).

        Параметры имитируют факторы, влияющие на кодирование у человека:
          - emotion          : эмоциональная окраска (амигдала усиливает запоминание)
          - deep_processing  : глубокая обработка (теория уровней обработки Крейка и Локхарта)
          - context          : контекст (место, время, состояние) — помогает потом вспомнить
          - mem_type         : тип — эпизодическая (события), семантическая (факты), процедурная
        """
        emb = get_embedding(content)  # кодируем смысл в вектор

        # Базовая сила следа. Эмоции дают бонус (сильные переживания помнятся лучше).
        strength = 1.0 + max(0.0, emotion) * 0.5

        # Глубокая обработка или наличие контекста тоже укрепляет след.
        if deep_processing or context:
            strength += 0.4

        return {
            "content": content,  # исходный текст (то, что «запомнили»)
            "embedding": emb,  # векторное представление
            "timestamp": self.now,  # когда закодировали
            "type": mem_type,  # episodic / semantic / procedural
            "emotion": float(np.clip(emotion, -1, 1)),  # от -1 (плохо) до +1 (хорошо)
            "context": context or {},  # дополнительные ключи для извлечения
            "strength": strength,  # сила следа (влияет на вероятность вспомнить)
            "accesses": 0,  # сколько раз уже извлекали (реконсолидация)
            "last_access": self.now,  # последнее обращение
        }

    def encode(
        self,
        information: str,
        context: Optional[Dict] = None,
        emotion: float = 0.0,
        mem_type: str = "episodic",
        deep: bool = False,
    ) -> Dict[str, Any]:
        """
        КОДИРОВАНИЕ — первый этап памяти.

        Информация попадает сначала в сенсорную память, затем в рабочую.
        Без внимания и осмысленной обработки она почти не перейдёт дальше
        (как в реальной жизни: мы видим/слышим многое, но запоминаем мало).
        """
        mem = self._make_memory(information, mem_type, emotion, context, deep)

        # Сначала в сенсорный буфер (очень кратко)
        self.sensory.append(mem)

        # Затем в рабочую память. Если она полная — самое старое вытесняется.
        # Это имитирует ограниченность внимания и рабочей памяти.
        self.working.append(mem)

        return mem

    def rehearse(self, query: Optional[str] = None):
        """
        ПОВТОРЕНИЕ (rehearsal) в рабочей памяти.

        Человек может «прокручивать» информацию в голове (фонологическая петля).
        Каждое повторение немного укрепляет след и увеличивает шанс перехода
        в долговременную память.
        """
        if not self.working:
            return
        for m in self.working:
            m["strength"] = min(
                3.0, m["strength"] * 1.15
            )  # укрепляем, но не бесконечно
            m["accesses"] += 1

    def consolidate(self, during_sleep: bool = False):
        """
        КОНСОЛИДАЦИЯ — перевод из рабочей памяти в долговременную.

        В мозге это происходит с участием гиппокампа, особенно активно во сне
        (replay — повторное проигрывание следов).

        Также моделируется ИНТЕРФЕРЕНЦИЯ: похожие воспоминания мешают друг другу
        (проактивная и ретроактивная интерференция).
        """
        for mem in list(self.working):
            # Интерференция: если есть очень похожий след — оба немного ослабевают
            for existing in self.long_term:
                sim = cosine_sim(mem["embedding"], existing["embedding"])
                if sim > 0.82:  # порог «слишком похоже»
                    existing["strength"] *= 0.92
                    mem["strength"] *= 0.95

            # Переносим в долговременную память
            self.long_term.append(mem)

        # Рабочая память очищается (как после того, как перестали держать в уме)
        self.working.clear()

        if during_sleep:
            # Во сне следы дополнительно укрепляются (консолидация)
            for m in self.long_term:
                m["strength"] = min(4.0, m["strength"] * 1.25)

    def retrieve(
        self, query: str, k: int = 5, reconstruct: bool = True
    ) -> Dict[str, Any]:
        """
        ИЗВЛЕЧЕНИЕ (retrieval) — поиск воспоминания по запросу.

        Память РЕКОНСТРУКТИВНА: мы не достаём точную запись, а собираем её заново
        из фрагментов, используя ключи (query), эмоции, давность и силу следа.

        Оценка релевантности учитывает:
          - семантическое сходство (косинус)
          - давность (recency) — недавнее помнится лучше
          - эмоции (эмоциональные события ярче)
          - частоту предыдущих обращений (эффект тестирования / реконсолидация)
          - текущую силу следа
        """
        q_emb = get_embedding(query)
        candidates = list(self.working) + self.long_term  # ищем везде

        scored = []
        for mem in candidates:
            sim = cosine_sim(q_emb, mem["embedding"])

            # Давность в часах → экспоненциальный спад (свежее = лучше)
            age_h = (self.now - mem["timestamp"]).total_seconds() / 3600.0
            recency = np.exp(-age_h / 48.0)

            emotion_boost = 1.0 + 0.6 * abs(mem["emotion"])  # эмоции помогают
            access_boost = (
                1.0 + 0.08 * mem["accesses"]
            )  # чем чаще вспоминали, тем легче

            score = sim * recency * emotion_boost * access_boost * mem["strength"]
            scored.append((score, mem))

        # Сортируем по убыванию релевантности и берём топ-k
        scored.sort(key=lambda x: x[0], reverse=True)
        top = [m for score, m in scored[:k] if score > 0.15]  # отсекаем совсем слабые

        # РЕКОНСОЛИДАЦИЯ: при каждом извлечении след немного укрепляется
        # (в мозге воспоминание становится пластичным и может измениться)
        for m in top:
            m["accesses"] += 1
            m["last_access"] = self.now
            m["strength"] = min(4.0, m["strength"] * 1.08)

        result = {
            "query": query,
            "fragments": [  # сырые фрагменты, из которых собирается воспоминание
                {
                    "content": m["content"],
                    "type": m["type"],
                    "emotion": m["emotion"],
                    "strength": round(m["strength"], 2),
                }
                for m in top
            ],
        }

        if reconstruct and top:
            # Собираем «воспоминание» из фрагментов (реконструкция)
            result["reconstructed"] = self._reconstruct(top, query)

        return result

    def _reconstruct(self, memories: List[Dict], query: str) -> str:
        """
        РЕКОНСТРУКЦИЯ воспоминания.

        Человеческая память не хранит точную копию события.
        Мозг каждый раз заново собирает историю из кусочков + текущих ожиданий
        и контекста. Поэтому возникают ложные воспоминания и искажения.

        Здесь — простая склейка. В реальном проекте этот метод можно заменить
        на вызов большой языковой модели (LLM), которая «дорасскажет» связную историю.
        """
        parts = [m["content"] for m in memories]
        rec = " | ".join(parts)

        # --- Пример, как подключить LLM (раскомментируйте и настройте) ---
        # prompt = (
        #     f"Собери связное, естественное воспоминание по запросу '{query}' "
        #     f"из следующих фрагментов: {parts}. "
        #     "Добавь правдоподобный контекст, но не выдумывай факты сверх имеющихся."
        # )
        # rec = your_llm_client.generate(prompt)

        return f"[Реконструкция воспоминания] {rec}"

    def forget(self, hours_passed: float = 1.0, decay: float = 0.04):
        """
        ЗАБЫВАНИЕ.

        Реализует кривую забывания Эббингауза: без повторения информация
        быстро теряется (экспоненциальный спад).

        Следы, которые часто извлекали, забываются медленнее.
        Если сила падает ниже порога — след считается забытым и удаляется.
        """
        self.now += timedelta(hours=hours_passed)  # сдвигаем время симуляции

        keep = []
        for mem in self.long_term:
            age_h = (self.now - mem["timestamp"]).total_seconds() / 3600.0

            # Чем больше обращений — тем медленнее забывается
            retention = mem["strength"] * np.exp(
                -decay * age_h / (1 + 0.3 * mem["accesses"])
            )

            if retention > 0.12:  # порог «ещё помним»
                mem["strength"] = retention
                keep.append(mem)
            # иначе след исчезает (забыт)

        self.long_term = keep

    def simulate_sleep(self, hours: float = 8.0):
        """
        СИМУЛЯЦИЯ СНА.

        Во сне происходит важная консолидация (особенно медленный сон и REM).
        Неважные следы могут немного ослабнуть, важные — укрепиться.
        """
        self.consolidate(during_sleep=True)
        self.forget(hours_passed=hours, decay=0.015)  # во сне забывание мягче

    def stats(self) -> Dict:
        """Простая статистика текущего состояния памяти (для отладки)."""
        return {
            "working": len(self.working),
            "long_term": len(self.long_term),
            "avg_strength": (
                float(np.mean([m["strength"] for m in self.long_term]))
                if self.long_term
                else 0.0
            ),
        }


